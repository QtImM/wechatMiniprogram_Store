"""固定当前发布所需全部迁移的版本与 LF/UTF-8 校验和。"""
import argparse
from pathlib import Path
from prepare_database import migrations
from delivery_backup import ROOT

TARGET = ROOT / 'shop-backend/shop-server/src/main/resources/delivery-migrations.properties'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = '# Generated by scripts/generate_migration_manifest.py; UTF-8 LF hashes\n'
    content += ''.join(version + '=' + checksum + '\n' for version, _, _, checksum in migrations())
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != content:
            raise ValueError('发布迁移清单与 SQL 不一致，请重新生成并审查')
        print('完整迁移清单校验通过')
    else:
        TARGET.write_text(content, encoding='utf-8')
        print('已生成完整迁移清单')


if __name__ == '__main__':
    main()
